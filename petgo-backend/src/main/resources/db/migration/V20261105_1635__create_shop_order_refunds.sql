-- v1.4.2 shop Story 4.1：取消退款单（架构 D-15、P-8 ⑨；决策 S-5 / S-8 / S-9 / m1 / m2）。
--
-- ① 不复用 return_requests：退货单按退货行与回程运费算 quote，与取消退款口径不同（D-15）。
--    金额只在 ShopRefundCalculator（P-1）算，本表只落结果。
-- ② 部分取消复用 shop_order_lines.refunded_qty、订单累计复用 shop_orders.refunded_total / refunded_coin（I5），
--    本表不另建同义累计列。
-- ③ 商家平台目前只扫 return_requests，看不到本表 —— 门店返佣的取消扣回登记为遗留（S-5）；
--    商家仓扫描改造不在本线，门店结算正式开始前补。
-- ④ 收款账户 payout_account_enc 与户名 payout_account_holder_enc 为 AES-GCM 加密列
--    （沿用 pay/refund/crypto/EncryptedStringConverter，同 return_requests.payout_account）。
--    注销时由 ShopAccountDeletionService 置空（D1/D2）。
-- ⑤ 架构 D-15 的状态值 COIN_REFUNDED 无写入方（币段在建单同事务即退、现金为 0 直接 COMPLETED），不建。
-- 整数列 INTEGER、金额 BIGINT、对外只用 public_token；无小整型列。

CREATE TABLE shop_order_refunds (
    id                        BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_token              VARCHAR(32)  NOT NULL,
    order_id                  BIGINT       NOT NULL REFERENCES shop_orders (id),
    scope                     VARCHAR(16)  NOT NULL,
    order_line_id             BIGINT       REFERENCES shop_order_lines (id),
    line_qty                  INTEGER,
    reason                    VARCHAR(32)  NOT NULL,
    goods_refund              BIGINT       NOT NULL DEFAULT 0,
    shipping_refund           BIGINT       NOT NULL DEFAULT 0,
    insurance_refund          BIGINT       NOT NULL DEFAULT 0,
    total_refund              BIGINT       NOT NULL,
    coin_refund               BIGINT       NOT NULL,
    cash_refund               BIGINT       NOT NULL,
    cash_destination          VARCHAR(16),
    payout_channel            VARCHAR(16),
    payout_account_enc        VARCHAR(255),          -- AES-GCM（EncryptedStringConverter）
    payout_account_holder_enc VARCHAR(255),          -- AES-GCM
    payout_fee                BIGINT       NOT NULL DEFAULT 0,
    compensation_amount       BIGINT       NOT NULL DEFAULT 0,
    status                    VARCHAR(24)  NOT NULL,
    destination_chosen_at     TIMESTAMPTZ,
    paid_out_at               TIMESTAMPTZ,
    payout_failed_at          TIMESTAMPTZ,
    payout_fail_note          VARCHAR(200),
    destination_reminded_at   TIMESTAMPTZ,
    created_by_admin_id       BIGINT,
    version                   BIGINT       NOT NULL DEFAULT 0,
    created_at                TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at                TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_shop_order_refunds_token UNIQUE (public_token),
    CONSTRAINT ck_shop_order_refunds_scope CHECK (scope IN ('WHOLE','LINE','COMPENSATION')),
    CONSTRAINT ck_shop_order_refunds_line_shape CHECK (
        (scope = 'LINE' AND order_line_id IS NOT NULL AND line_qty > 0)
     OR (scope <> 'LINE' AND order_line_id IS NULL AND line_qty IS NULL)),
    CONSTRAINT ck_shop_order_refunds_reason CHECK (reason IN (
        'OUT_OF_STOCK','WAYBILL_FAILED','PICKUP_FAILED','COURIER_FAULT',
        'USER_FAULT_RETURNED','LOST_DAMAGED','LATE_PAYMENT')),
    CONSTRAINT ck_shop_order_refunds_amounts CHECK (
        goods_refund >= 0 AND shipping_refund >= 0 AND insurance_refund >= 0
        AND coin_refund >= 0 AND cash_refund >= 0 AND payout_fee >= 0 AND compensation_amount >= 0
        AND coin_refund + cash_refund = total_refund
        AND goods_refund + shipping_refund + insurance_refund = total_refund),
    CONSTRAINT ck_shop_order_refunds_destination CHECK (cash_destination IS NULL OR cash_destination IN ('TO_PAWCOIN','TO_BANK')),
    CONSTRAINT ck_shop_order_refunds_channel CHECK (payout_channel IS NULL OR payout_channel IN ('BCA','OVO','GOPAY')),
    CONSTRAINT ck_shop_order_refunds_status CHECK (status IN (
        'AWAITING_DESTINATION','PAYOUT_PENDING','PAYOUT_FAILED','COMPLETED'))
);
CREATE INDEX ix_shop_order_refunds_order ON shop_order_refunds (order_id, created_at);
CREATE INDEX ix_shop_order_refunds_open ON shop_order_refunds (status, created_at)
    WHERE status IN ('AWAITING_DESTINATION','PAYOUT_PENDING','PAYOUT_FAILED');
