-- event：ISSUED 发放 | LOCKED 下单占用 | RELEASED 取消退回可用 | USED 付款使用 | VOIDED 作废（停券作废 / 注销 / 退回时模板已停用作废）。
-- user_coupon_id ON DELETE CASCADE（注销级联）；order_id ON DELETE SET NULL（同 user_coupons.locked_order_id，不挡清库）。
CREATE TABLE user_coupon_events (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_coupon_id  BIGINT      NOT NULL REFERENCES user_coupons (id) ON DELETE CASCADE,
    event           VARCHAR(16) NOT NULL,
    order_id        BIGINT      REFERENCES shop_orders (id) ON DELETE SET NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_user_coupon_events_event CHECK (event IN ('ISSUED', 'LOCKED', 'RELEASED', 'USED', 'VOIDED'))
);
CREATE INDEX idx_user_coupon_events_coupon ON user_coupon_events (user_coupon_id, created_at);
CREATE INDEX idx_user_coupon_events_order ON user_coupon_events (order_id) WHERE order_id IS NOT NULL;
