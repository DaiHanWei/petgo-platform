-- v1.4.2 shop · Story 1.1 · 迁移 ⑧（D-9、P-8 ⑧）：Biteship 报价落库与复用
--
-- 复用键 (dest_postal_code, items_hash, origin_postal_code, provider_mode)，取 expires_at > now() 的最新一行；
-- provider_mode 进复用键：防止 stub / sandbox 报价切 live 后被当真报价复用。
-- 「不可配送」也落库（serviceable=false、lowest_price=null）；「询价失败」不落库。
-- 不加唯一约束、不加锁：并发下同键可能两次真调（各插一行），可接受。
-- response 存规范化后的 {"rates":[...],"noCourierCode":...}，不存 Biteship 原始响应。
-- 订单引用列 shop_orders.shipping_quote_id 属 Story 3.2，不在本迁移。
-- 每日清理 created_at < now() - 2 days（ShippingQuoteCleanupJob；被订单引用的排除由 3.2 补）。

CREATE TABLE shipping_quotes (
    id                 BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_token       VARCHAR(32) NOT NULL,
    user_id            BIGINT      REFERENCES users (id) ON DELETE SET NULL,  -- 首个请求者，仅审计；复用不看它
    provider_mode      VARCHAR(8)  NOT NULL,                                  -- STUB | SANDBOX | LIVE
    origin_postal_code VARCHAR(5)  NOT NULL,
    dest_postal_code   VARCHAR(5)  NOT NULL,
    items_hash         VARCHAR(64) NOT NULL,
    serviceable        BOOLEAN     NOT NULL,
    response           JSONB       NOT NULL,                                  -- 规范化后的快递列表
    lowest_price       BIGINT,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at         TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_shipping_quotes_public_token UNIQUE (public_token),
    CONSTRAINT ck_shipping_quotes_mode CHECK (provider_mode IN ('STUB', 'SANDBOX', 'LIVE')),
    CONSTRAINT ck_shipping_quotes_lowest CHECK (
        (serviceable AND lowest_price IS NOT NULL AND lowest_price >= 0)
        OR (NOT serviceable AND lowest_price IS NULL)),
    CONSTRAINT ck_shipping_quotes_expiry CHECK (expires_at > created_at)
);

CREATE INDEX idx_shipping_quotes_reuse
    ON shipping_quotes (dest_postal_code, items_hash, origin_postal_code, provider_mode, expires_at DESC);
CREATE INDEX idx_shipping_quotes_created ON shipping_quotes (created_at);
