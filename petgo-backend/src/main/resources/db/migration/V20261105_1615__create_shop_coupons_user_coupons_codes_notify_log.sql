-- v1.4.2 shop · Story 2.1 · 迁移 ⑦（P-8 ⑦，D-1 ~ D-4、I8）：券模板 / 兑换码 / 用户券 / 快过期提醒去重 四张表。
--
-- 🔴 已过期不落库，由 valid_until 现算（D-2）：AVAILABLE 且 valid_until <= now 即过期，不存在定时改状态的任务。
-- 🔴 用户券状态只经 CouponLedgerService（P-2）；全仓库唯一写这张表的是 UserCouponLedgerDao（守卫测试强制）。
-- 🔴 注销只匿名化 users 行，ON DELETE CASCADE 在注销路径不触发，注销联动见 Story 2.1 AC7
--    （ShopAccountDeletionService：可用券 VOIDED、提醒日志删除）。
-- ⚠️ user_coupons 刻意不加「LOCKED ⇔ locked_order_id 非空」CHECK：删订单时 ON DELETE SET NULL 会违反它、
--    反过来挡住删除；一致性由 service 保证。
-- 整数列 INTEGER、金额 BIGINT，禁止 SMALLINT；对外标识 public_token（券模板、用户券）。

-- ① 券模板
CREATE TABLE shop_coupons (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_token    VARCHAR(32)  NOT NULL,
    kind            VARCHAR(16)  NOT NULL,                 -- DISCOUNT | FREE_SHIPPING
    name_id         VARCHAR(60)  NOT NULL,                 -- 券名（印尼语），运营录入
    name_en         VARCHAR(60)  NOT NULL,
    amount          BIGINT       NOT NULL,                 -- 满减额；免运券 = 每张减免封顶
    min_spend       BIGINT       NOT NULL DEFAULT 0,       -- 0 = 无门槛
    scope_type      VARCHAR(16)  NOT NULL DEFAULT 'ALL',   -- ALL | CATEGORY | PRODUCT
    scope_values    JSONB        NOT NULL DEFAULT '[]'::jsonb, -- 品类码或商品 public_token 数组
    acquire_type    VARCHAR(16)  NOT NULL,                 -- NEWBIE | CLAIM | CODE
    issue_start_at  TIMESTAMPTZ  NOT NULL,                 -- 发放期（能领 / 能兑 / 新人能发 / banner 能展示）
    issue_end_at    TIMESTAMPTZ  NOT NULL,
    valid_mode      VARCHAR(16)  NOT NULL,                 -- FIXED | RELATIVE
    valid_start_at  TIMESTAMPTZ,                           -- FIXED 用
    valid_end_at    TIMESTAMPTZ,
    valid_days      INTEGER,                               -- RELATIVE 用：领取后 N 天
    total_quantity  INTEGER,                               -- NULL = 不限
    issued_count    INTEGER      NOT NULL DEFAULT 0,
    per_user_limit  INTEGER      NOT NULL DEFAULT 1,
    status          VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',-- ACTIVE | STOPPED
    void_on_stop    BOOLEAN      NOT NULL DEFAULT FALSE,   -- 停用时是否选了「作废已领未用」（D-3 需要，D-1 未列，本 story 补）
    stopped_at      TIMESTAMPTZ,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_shop_coupons_public_token UNIQUE (public_token),
    CONSTRAINT ck_shop_coupons_kind CHECK (kind IN ('DISCOUNT', 'FREE_SHIPPING')),
    CONSTRAINT ck_shop_coupons_scope_type CHECK (scope_type IN ('ALL', 'CATEGORY', 'PRODUCT')),
    CONSTRAINT ck_shop_coupons_acquire_type CHECK (acquire_type IN ('NEWBIE', 'CLAIM', 'CODE')),
    CONSTRAINT ck_shop_coupons_valid_mode CHECK (valid_mode IN ('FIXED', 'RELATIVE')),
    CONSTRAINT ck_shop_coupons_status CHECK (status IN ('ACTIVE', 'STOPPED')),
    CONSTRAINT ck_shop_coupons_amount CHECK (amount > 0),
    CONSTRAINT ck_shop_coupons_min_spend CHECK (min_spend >= 0),
    CONSTRAINT ck_shop_coupons_discount_below_min CHECK (NOT (kind = 'DISCOUNT' AND min_spend > 0 AND amount >= min_spend)),
    CONSTRAINT ck_shop_coupons_issue_period CHECK (issue_end_at > issue_start_at),
    CONSTRAINT ck_shop_coupons_validity CHECK (
        (valid_mode = 'FIXED' AND valid_start_at IS NOT NULL AND valid_end_at IS NOT NULL
             AND valid_end_at > valid_start_at AND valid_days IS NULL)
        OR (valid_mode = 'RELATIVE' AND valid_days IS NOT NULL AND valid_days >= 1
             AND valid_start_at IS NULL AND valid_end_at IS NULL)),
    CONSTRAINT ck_shop_coupons_quantity CHECK (
        (total_quantity IS NULL OR total_quantity >= 1) AND issued_count >= 0
        AND (total_quantity IS NULL OR issued_count <= total_quantity)),
    CONSTRAINT ck_shop_coupons_per_user CHECK (per_user_limit >= 1),
    CONSTRAINT ck_shop_coupons_stopped CHECK ((status = 'STOPPED') = (stopped_at IS NOT NULL))
);
CREATE INDEX idx_shop_coupons_issuing ON shop_coupons (acquire_type, status, issue_start_at, issue_end_at);

-- ② 兑换码
CREATE TABLE shop_coupon_codes (
    id                   BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_id            BIGINT      NOT NULL REFERENCES shop_coupons (id),
    code                 VARCHAR(32) NOT NULL,          -- 大写规范化
    single_use           BOOLEAN     NOT NULL,
    redeemed_by_user_id  BIGINT      REFERENCES users (id) ON DELETE SET NULL,
    redeemed_at          TIMESTAMPTZ,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_shop_coupon_codes_code UNIQUE (code),
    CONSTRAINT ck_shop_coupon_codes_format CHECK (code ~ '^[A-Z0-9]{4,32}$'),
    CONSTRAINT ck_shop_coupon_codes_universal_never_redeemed CHECK (single_use OR redeemed_at IS NULL)
);
CREATE INDEX idx_shop_coupon_codes_coupon ON shop_coupon_codes (coupon_id);

-- ③ 用户券（状态只经 CouponLedgerService，P-2）
CREATE TABLE user_coupons (
    id                  BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_token        VARCHAR(32) NOT NULL,
    user_id             BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    coupon_id           BIGINT      NOT NULL REFERENCES shop_coupons (id),
    source              VARCHAR(16) NOT NULL,           -- NEWBIE | CLAIM | CODE | BANNER | REISSUE
    status              VARCHAR(16) NOT NULL DEFAULT 'AVAILABLE', -- AVAILABLE | LOCKED | USED | VOIDED
    locked_order_id     BIGINT      REFERENCES shop_orders (id) ON DELETE SET NULL,
    used_order_id       BIGINT      REFERENCES shop_orders (id) ON DELETE SET NULL,
    valid_from          TIMESTAMPTZ NOT NULL,           -- 领取时按模板物化
    valid_until         TIMESTAMPTZ NOT NULL,
    claimed_at          TIMESTAMPTZ NOT NULL,
    expiry_notified_at  TIMESTAMPTZ,                    -- 2.3：每张券只提醒一次（I8）
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_user_coupons_public_token UNIQUE (public_token),
    CONSTRAINT ck_user_coupons_source CHECK (source IN ('NEWBIE', 'CLAIM', 'CODE', 'BANNER', 'REISSUE')),
    CONSTRAINT ck_user_coupons_status CHECK (status IN ('AVAILABLE', 'LOCKED', 'USED', 'VOIDED')),
    CONSTRAINT ck_user_coupons_validity CHECK (valid_until > valid_from)
);
CREATE INDEX idx_user_coupons_user_status_valid ON user_coupons (user_id, status, valid_until);
CREATE INDEX idx_user_coupons_coupon_user ON user_coupons (coupon_id, user_id);
CREATE INDEX idx_user_coupons_locked_order ON user_coupons (locked_order_id) WHERE locked_order_id IS NOT NULL;
CREATE INDEX idx_user_coupons_expiry_scan ON user_coupons (valid_until)
    WHERE status = 'AVAILABLE' AND expiry_notified_at IS NULL;

-- ④ 快过期提醒去重（2.3 使用）
CREATE TABLE coupon_expiry_notify_log (
    user_id       BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    wib_date      DATE        NOT NULL,
    coupon_count  INTEGER     NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_coupon_expiry_notify_log PRIMARY KEY (user_id, wib_date),
    CONSTRAINT ck_coupon_expiry_notify_log_count CHECK (coupon_count >= 1)
);
CREATE INDEX idx_coupon_expiry_notify_log_date ON coupon_expiry_notify_log (wib_date);
