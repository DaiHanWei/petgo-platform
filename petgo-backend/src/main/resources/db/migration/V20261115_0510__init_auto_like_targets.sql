-- V1.5.0 likes Story 2.1（PRD 自动点赞 FR-213 / FR-215 / FR-221 / FR-223）：自动点赞目标集 + 「检查过」记录，一帖一行。
-- post_id 唯一 = 每帖只检查一次；离开（left_at 非空）后不再回来。author_id 不设外键（同 auto_comment_logs.virtual_user_id，不挡注销路径）。
CREATE TABLE auto_like_targets (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id             BIGINT       NOT NULL UNIQUE REFERENCES content_posts (id) ON DELETE CASCADE,
    author_id           BIGINT       NOT NULL,
    post_created_at     TIMESTAMPTZ  NOT NULL,
    checked_at          TIMESTAMPTZ  NOT NULL,
    like_count_at_check INTEGER      NOT NULL,
    joined              BOOLEAN      NOT NULL,
    left_at             TIMESTAMPTZ,
    leave_reason        VARCHAR(24),
    failed_attempts     INTEGER      NOT NULL DEFAULT 0,
    last_liked_at       TIMESTAMPTZ,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_auto_like_targets_leave_reason CHECK (leave_reason IN
        ('AT_TARGET_ON_CHECK', 'HOLDOUT', 'REACHED_TARGET', 'MAX_AGE', 'POST_GONE', 'NO_IDENTITY', 'TOO_MANY_FAILURES')),
    CONSTRAINT ck_auto_like_targets_left CHECK ((left_at IS NULL) = (leave_reason IS NULL)),
    CONSTRAINT ck_auto_like_targets_not_joined CHECK (joined OR left_at IS NOT NULL)
);

CREATE INDEX ix_auto_like_targets_open ON auto_like_targets (author_id, post_created_at, post_id)
    WHERE joined AND left_at IS NULL;

COMMENT ON TABLE auto_like_targets IS '自动点赞目标集与检查记录（V1.5.0）：每帖在发帖 36–60 小时时检查一次，赞数不足目标的进集合；离开后不再回来';
COMMENT ON COLUMN auto_like_targets.id IS '主键';
COMMENT ON COLUMN auto_like_targets.post_id IS '被检查的帖子 id（唯一：每帖只检查一次）';
COMMENT ON COLUMN auto_like_targets.author_id IS '帖子作者 id（不设外键）；排期时按作者轮流';
COMMENT ON COLUMN auto_like_targets.post_created_at IS '帖子发帖时间（冗余）：排期最老优先与 7 天关闭不回表';
COMMENT ON COLUMN auto_like_targets.checked_at IS '检查时刻（= 本轮开始时刻，UTC）';
COMMENT ON COLUMN auto_like_targets.like_count_at_check IS '检查时的展示赞数（真人 + 虚拟 + 自动），成效对比用';
COMMENT ON COLUMN auto_like_targets.joined IS '是否进入目标集（false = 只留检查痕迹：对照组或检查时已达标）';
COMMENT ON COLUMN auto_like_targets.left_at IS '离开目标集的时刻；未进集合的行 = checked_at；为空 = 仍在集合';
COMMENT ON COLUMN auto_like_targets.leave_reason IS '离开原因：AT_TARGET_ON_CHECK / HOLDOUT / REACHED_TARGET / MAX_AGE / POST_GONE / NO_IDENTITY / TOO_MANY_FAILURES';
COMMENT ON COLUMN auto_like_targets.failed_attempts IS '失败次数（只计未被叫停的轮次里的 FAILED）；达到上限在下一轮计划开始时离开';
COMMENT ON COLUMN auto_like_targets.last_liked_at IS '最近一次自动点赞成功时刻：同一作者多帖时按它轮流';
COMMENT ON COLUMN auto_like_targets.created_at IS '行创建时间（UTC）';
COMMENT ON COLUMN auto_like_targets.updated_at IS '行更新时间（UTC）';
