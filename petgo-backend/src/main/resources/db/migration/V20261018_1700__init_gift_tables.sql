-- ---------------------------------------------------------------------------
-- 礼物目录（AD-1）：只下线不物理删除（订单 FK 指向它）。
-- ---------------------------------------------------------------------------
CREATE TABLE gift_catalog (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_token  VARCHAR(32)   NOT NULL,
    name_en       VARCHAR(40)   NOT NULL,
    name_id       VARCHAR(40)   NOT NULL,
    icon_url      VARCHAR(1024) NOT NULL,
    price         BIGINT        NOT NULL,
    for_cat       BOOLEAN       NOT NULL DEFAULT false,
    for_dog       BOOLEAN       NOT NULL DEFAULT false,
    for_other     BOOLEAN       NOT NULL DEFAULT false,
    kind          VARCHAR(16)   NOT NULL,
    min_level     INT           NULL,
    sort_order    INT           NOT NULL DEFAULT 0,
    status        VARCHAR(16)   NOT NULL DEFAULT 'ONLINE',
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_by    BIGINT        NULL,
    CONSTRAINT uq_gift_catalog_public_token UNIQUE (public_token),
    CONSTRAINT ck_gift_catalog_price CHECK (price >= 100),
    CONSTRAINT ck_gift_catalog_kind CHECK (kind IN ('NORMAL', 'EXCLUSIVE')),
    CONSTRAINT ck_gift_catalog_status CHECK (status IN ('ONLINE', 'OFFLINE')),
    CONSTRAINT ck_gift_catalog_exclusive_level CHECK (
        (kind = 'EXCLUSIVE' AND min_level >= 1) OR (kind = 'NORMAL' AND min_level IS NULL))
);

-- App 目录接口：只取 ONLINE，按价位 / 排序值分组。
CREATE INDEX ix_gift_catalog_online ON gift_catalog (status, price, sort_order);

COMMENT ON TABLE gift_catalog IS
    '礼物目录（V1.4.0 AD-1，FR-148 / AB-35）：只下线不物理删除；首批礼物由运营在后台录入，迁移不 seed。';
COMMENT ON COLUMN gift_catalog.public_token IS '不可枚举对外标识（App giftToken，32 位 base62）。';
COMMENT ON COLUMN gift_catalog.name_en IS '礼物英文名（App 按账号语言取 EN / ID，不渲染后端显示串）。';
COMMENT ON COLUMN gift_catalog.name_id IS '礼物印尼语名。';
COMMENT ON COLUMN gift_catalog.icon_url IS '礼物图标公共 URL（OSS 公共目录）。';
COMMENT ON COLUMN gift_catalog.price IS '单价（IDR，≥100）。改价只影响新订单，已下单按订单快照。';
COMMENT ON COLUMN gift_catalog.for_cat IS '适用猫；for_cat / for_dog / for_other 三者皆 false = 通用。目录组内排序：适用该物种 → 通用 → 其他。';
COMMENT ON COLUMN gift_catalog.for_dog IS '适用狗（见 for_cat）。';
COMMENT ON COLUMN gift_catalog.for_other IS '适用其他物种（见 for_cat）。';
COMMENT ON COLUMN gift_catalog.kind IS 'NORMAL 普通礼物 / EXCLUSIVE 专属礼物（按送礼人等级解锁）。';
COMMENT ON COLUMN gift_catalog.min_level IS '专属礼物解锁等级（EXCLUSIVE 必填 ≥1；NORMAL 必须为 NULL）。';
COMMENT ON COLUMN gift_catalog.sort_order IS '同组内排序值（升序，同值按 id 升序）。';
COMMENT ON COLUMN gift_catalog.status IS 'ONLINE 上架 / OFFLINE 下线（下线不影响已收礼物的展示）。';
COMMENT ON COLUMN gift_catalog.updated_by IS '最近一次修改的后台账号 id（Story 3.1 写入；不加 FK，审计另记）。';

-- ---------------------------------------------------------------------------
-- 送礼订单（AD-2）：每笔幂等（idem_key），礼物信息与宠物名下单时快照。
-- ---------------------------------------------------------------------------
CREATE TABLE gift_orders (
    id                  BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_token        VARCHAR(32)   NOT NULL,
    sender_id           BIGINT        NOT NULL,
    pet_id              BIGINT        NULL REFERENCES pet_profiles (id) ON DELETE SET NULL,
    owner_id            BIGINT        NOT NULL,
    pet_name            VARCHAR(20)   NOT NULL,
    gift_id             BIGINT        NOT NULL REFERENCES gift_catalog (id),
    gift_name_en        VARCHAR(40)   NOT NULL,
    gift_name_id        VARCHAR(40)   NOT NULL,
    gift_icon_url       VARCHAR(1024) NOT NULL,
    unit_price          BIGINT        NOT NULL,
    quantity            INT           NOT NULL,
    total               BIGINT        NOT NULL,
    channel             VARCHAR(16)   NOT NULL,
    payment_intent_id   BIGINT        NULL,
    status              VARCHAR(32)   NOT NULL,
    undelivered_reason  VARCHAR(24)   NULL,
    refund_attempts     INT           NOT NULL DEFAULT 0,
    refund_error        VARCHAR(64)   NULL,
    source              VARCHAR(16)   NOT NULL,
    idem_key            VARCHAR(96)   NOT NULL,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    delivered_at        TIMESTAMPTZ   NULL,
    refunded_at         TIMESTAMPTZ   NULL,
    CONSTRAINT uq_gift_orders_public_token UNIQUE (public_token),
    CONSTRAINT uq_gift_orders_payment_intent UNIQUE (payment_intent_id),
    CONSTRAINT uq_gift_orders_idem_key UNIQUE (idem_key),
    CONSTRAINT ck_gift_orders_unit_price CHECK (unit_price >= 100),
    CONSTRAINT ck_gift_orders_quantity CHECK (quantity BETWEEN 1 AND 99),
    CONSTRAINT ck_gift_orders_total CHECK (total = unit_price * quantity),
    CONSTRAINT ck_gift_orders_channel CHECK (channel IN ('PAWCOIN', 'QRIS')),
    CONSTRAINT ck_gift_orders_status CHECK (status IN ('PENDING', 'DELIVERED', 'EXPIRED', 'FAILED',
        'UNDELIVERED_REFUND_PENDING', 'UNDELIVERED_REFUNDED', 'REFUND_MANUAL')),
    CONSTRAINT ck_gift_orders_undelivered_reason CHECK (undelivered_reason IN
        ('PET_DELETED', 'OWNER_DELETED', 'SENDER_BLOCKED')),
    CONSTRAINT ck_gift_orders_source CHECK (source IN ('diary_tab', 'content_detail', 'gift_page'))
);

-- 我的送礼记录（Story 2.3）游标。
CREATE INDEX ix_gift_orders_sender_created ON gift_orders (sender_id, created_at DESC, id DESC);
-- 后台抽屉「收到」子列表（Story 3.2）游标。
CREATE INDEX ix_gift_orders_owner_created ON gift_orders (owner_id, created_at DESC, id DESC);
-- 按宠物 + 状态（展示核对 / 删档排查）。
CREATE INDEX ix_gift_orders_pet_status ON gift_orders (pet_id, status);
-- 退回重试扫描 / 后台异常单（Story 1.2 / 3.2）。
CREATE INDEX ix_gift_orders_status ON gift_orders (status);

