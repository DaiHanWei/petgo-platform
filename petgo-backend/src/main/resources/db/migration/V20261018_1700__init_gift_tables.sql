-- ---------------------------------------------------------------------------
-- 展示汇总（AD-3）：只在交付同事务维护，只含 DELIVERED；随宠物级联删除。
-- ---------------------------------------------------------------------------
CREATE TABLE gift_pet_wall (
    pet_id         BIGINT        NOT NULL REFERENCES pet_profiles (id) ON DELETE CASCADE,
    gift_id        BIGINT        NOT NULL REFERENCES gift_catalog (id),
    unit_price     BIGINT        NOT NULL,
    gift_name_en   VARCHAR(40)   NOT NULL,
    gift_name_id   VARCHAR(40)   NOT NULL,
    gift_icon_url  VARCHAR(1024) NOT NULL,
    count          BIGINT        NOT NULL,
    CONSTRAINT pk_gift_pet_wall PRIMARY KEY (pet_id, gift_id, unit_price),
    CONSTRAINT ck_gift_pet_wall_count CHECK (count >= 1)
);

COMMENT ON TABLE gift_pet_wall IS
    '礼物墙汇总（V1.4.0 AD-3，FR-149）：同一礼物改价后按价位分组；交付同事务 upsert，只含 DELIVERED；随宠物级联删除。'
    '宠物收到礼物总价值 = Σ unit_price × count。';
COMMENT ON COLUMN gift_pet_wall.unit_price IS '成交单价（IDR，订单快照）。';
COMMENT ON COLUMN gift_pet_wall.gift_name_en IS '首次送达时的礼物英文名快照（后续 upsert 不覆盖）。';
COMMENT ON COLUMN gift_pet_wall.gift_name_id IS '首次送达时的礼物印尼语名快照（后续 upsert 不覆盖）。';
COMMENT ON COLUMN gift_pet_wall.gift_icon_url IS '首次送达时的礼物图标快照（后续 upsert 不覆盖）。';
COMMENT ON COLUMN gift_pet_wall.count IS '该宠物在此礼物 + 价位下累计收到的个数（≥1）。';

CREATE TABLE gift_pet_supporters (
    pet_id        BIGINT       NOT NULL REFERENCES pet_profiles (id) ON DELETE CASCADE,
    sender_id     BIGINT       NOT NULL,
    total_amount  BIGINT       NOT NULL,
    gift_count    BIGINT       NOT NULL,
    last_sent_at  TIMESTAMPTZ  NOT NULL,
    CONSTRAINT pk_gift_pet_supporters PRIMARY KEY (pet_id, sender_id)
);

-- 粉丝榜：累计金额降序，同额按最近送礼降序。
CREATE INDEX ix_gift_pet_supporters_rank ON gift_pet_supporters (pet_id, total_amount DESC, last_sent_at DESC);

COMMENT ON TABLE gift_pet_supporters IS
    '粉丝榜汇总（V1.4.0 AD-3，FR-149）：交付同事务 upsert，只含 DELIVERED；随宠物级联删除。'
    'sender_id 不加 FK（送礼人注销后显示「已注销用户」）。';
COMMENT ON COLUMN gift_pet_supporters.sender_id IS '送礼人 users.id（不加 FK）。';
COMMENT ON COLUMN gift_pet_supporters.total_amount IS '该送礼人给此宠物的累计送达金额（IDR）。';
COMMENT ON COLUMN gift_pet_supporters.gift_count IS '该送礼人给此宠物累计送达的礼物个数（Σ quantity）。';
COMMENT ON COLUMN gift_pet_supporters.last_sent_at IS '最近一次送达时刻（UTC，同额排序用）。';
