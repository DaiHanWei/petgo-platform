-- V1.5.0 likes Story 2.2（PRD 自动点赞 FR-212 / FR-214 / FR-219，附录 A）：自动点赞的轮次与每条计划的赞。
--
-- auto_like_runs：一槽（WIB 日期 + 早 / 晚）一行。uq (run_date, slot) = 同一槽只排一次（多实例防重）。
--   ACTIVE   已排期，窗口未结束
--   DONE     窗口结束（派发器收口）
--   STOPPED  被叫停：NO_POOL（无可用虚拟号）/ CONSECUTIVE_FAILURES（连续失败到上限）
--
-- auto_like_logs：一条计划的赞一行。uq (post_id, run_date, slot) = 同一帖同一槽最多一行 = 最多一个赞。
--   PLANNED         已排期，等待派发
--   MISSED          窗口结束仍未发出（不计失败）
--   LIKED           已点赞（virtual_user_id 为点赞的虚拟号）
--   REACHED_TARGET  派发时赞数已达目标，未点赞，帖子离开集合
--   SKIPPED_REVIEW  派发时帖子在审核中，本次跳过，帖子留在集合
--   POST_GONE       派发时帖子已删 / 非公开 / 作者状态不符，帖子离开集合
--   NO_IDENTITY     没有可用的虚拟号，帖子离开集合
--   FAILED          异常（error_code 记异常类名）；ALREADY_LIKED = 竞态下该号已赞，不计失败
--
-- 🔒 只存 id 与计数，不存帖子内容。virtual_user_id 不设外键（留档不挡账号注销）；不设指向 content_likes 的外键
--    （帖子物理删除会删赞）。

CREATE TABLE auto_like_runs (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_date             DATE         NOT NULL,
    slot                 VARCHAR(8)   NOT NULL,
    started_at           TIMESTAMPTZ  NOT NULL,
    window_end           TIMESTAMPTZ  NOT NULL,
    status               VARCHAR(8)   NOT NULL,
    stop_reason          VARCHAR(32),
    launch               BOOLEAN      NOT NULL,
    checked_count        INTEGER      NOT NULL DEFAULT 0,
    joined_count         INTEGER      NOT NULL DEFAULT 0,
    planned_count        INTEGER      NOT NULL DEFAULT 0,
    consecutive_failures INTEGER      NOT NULL DEFAULT 0,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_auto_like_runs_slot CHECK (slot IN ('MORNING', 'EVENING')),
    CONSTRAINT ck_auto_like_runs_status CHECK (status IN ('ACTIVE', 'DONE', 'STOPPED')),
    CONSTRAINT uq_auto_like_runs_slot UNIQUE (run_date, slot)
);

CREATE TABLE auto_like_logs (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id            BIGINT       NOT NULL REFERENCES auto_like_runs (id),
    post_id           BIGINT       NOT NULL REFERENCES content_posts (id) ON DELETE CASCADE,
    run_date          DATE         NOT NULL,
    slot              VARCHAR(8)   NOT NULL,
    planned_at        TIMESTAMPTZ  NOT NULL,
    window_end        TIMESTAMPTZ  NOT NULL,
    status            VARCHAR(16)  NOT NULL,
    virtual_user_id   BIGINT,
    like_count_before INTEGER,
    error_code        VARCHAR(64),
    attempted_at      TIMESTAMPTZ,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_auto_like_logs_slot CHECK (slot IN ('MORNING', 'EVENING')),
    CONSTRAINT ck_auto_like_logs_status CHECK (status IN
        ('PLANNED', 'MISSED', 'LIKED', 'REACHED_TARGET', 'SKIPPED_REVIEW', 'POST_GONE', 'NO_IDENTITY', 'FAILED')),
    CONSTRAINT uq_auto_like_logs_post_slot UNIQUE (post_id, run_date, slot)
);

CREATE INDEX ix_auto_like_logs_due ON auto_like_logs (planned_at) WHERE status = 'PLANNED';
CREATE INDEX ix_auto_like_logs_liked_at ON auto_like_logs (attempted_at) WHERE status = 'LIKED';
CREATE INDEX ix_auto_like_logs_run ON auto_like_logs (run_id);

COMMENT ON TABLE auto_like_runs IS '自动点赞轮次（V1.5.0）：一槽（WIB 日期 + 早 / 晚）一行，同一槽只排一次';
COMMENT ON COLUMN auto_like_runs.id IS '主键';
COMMENT ON COLUMN auto_like_runs.run_date IS '轮次日期（WIB）';
COMMENT ON COLUMN auto_like_runs.slot IS '槽：MORNING / EVENING';
COMMENT ON COLUMN auto_like_runs.started_at IS '本轮开始时刻（UTC）；帖子年龄按它算';
COMMENT ON COLUMN auto_like_runs.window_end IS '本轮派发窗口结束（= 开始 + spread-window）';
COMMENT ON COLUMN auto_like_runs.status IS 'ACTIVE / DONE / STOPPED';
COMMENT ON COLUMN auto_like_runs.stop_reason IS '叫停原因：NO_POOL / CONSECUTIVE_FAILURES';
COMMENT ON COLUMN auto_like_runs.launch IS '是否上线首轮（目标集表为空时的那一轮，检查上限放宽到 7 天）';
COMMENT ON COLUMN auto_like_runs.checked_count IS '本轮检查写入的帖子数';
COMMENT ON COLUMN auto_like_runs.joined_count IS '本轮检查后新进目标集的帖子数';
COMMENT ON COLUMN auto_like_runs.planned_count IS '本轮排期的赞数';
COMMENT ON COLUMN auto_like_runs.consecutive_failures IS '本轮当前连续失败条数（非失败结果清零）';
COMMENT ON COLUMN auto_like_runs.created_at IS '行创建时间（UTC）';
COMMENT ON COLUMN auto_like_runs.updated_at IS '行更新时间（UTC）';

COMMENT ON TABLE auto_like_logs IS '自动点赞留档（V1.5.0）：一条计划的赞一行；只存 id 与计数，不存帖子内容';
COMMENT ON COLUMN auto_like_logs.id IS '主键';
COMMENT ON COLUMN auto_like_logs.run_id IS '所属轮次';
COMMENT ON COLUMN auto_like_logs.post_id IS '目标帖子 id';
COMMENT ON COLUMN auto_like_logs.run_date IS '轮次日期（WIB，冗余）';
COMMENT ON COLUMN auto_like_logs.slot IS '槽（冗余）：MORNING / EVENING';
COMMENT ON COLUMN auto_like_logs.planned_at IS '计划派发时刻（本轮开始 + 随机 [0, spread-window)）';
COMMENT ON COLUMN auto_like_logs.window_end IS '本轮派发窗口结束（冗余，派发不用 JOIN）';
COMMENT ON COLUMN auto_like_logs.status IS 'PLANNED / MISSED / LIKED / REACHED_TARGET / SKIPPED_REVIEW / POST_GONE / NO_IDENTITY / FAILED';
COMMENT ON COLUMN auto_like_logs.virtual_user_id IS '点赞的虚拟号 id（不设外键）';
COMMENT ON COLUMN auto_like_logs.like_count_before IS '尝试前的展示赞数';
COMMENT ON COLUMN auto_like_logs.error_code IS '失败码：异常类名（截 64）或 ALREADY_LIKED；不存内容';
COMMENT ON COLUMN auto_like_logs.attempted_at IS '尝试时刻；日报按它的 WIB 日期数 LIKED';
COMMENT ON COLUMN auto_like_logs.created_at IS '行创建时间（UTC）';
COMMENT ON COLUMN auto_like_logs.updated_at IS '行更新时间（UTC）';
