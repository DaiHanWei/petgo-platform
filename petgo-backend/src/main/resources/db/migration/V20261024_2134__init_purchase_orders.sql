-- V1.4.1 商家平台对接（tailtopia-contract.md 第 2、5 节，FR-11～15、AD-17 / AD-19）：门店进货单。
--
-- 🔴 独立建表，不复用 shop_orders（2026-10-23 定）：返佣扫描只读 shop_orders，进货单天然不进返佣（FR-14）。
-- 四张表归 TailTopia，商家平台【不读不写】，只经内部接口（/internal/merchant/**）访问。
-- 对外标识一律 public_token（= 报文 po_token），自增 id 不出现在报文里。
-- merchant_store_id 存 merchant_stores.id（商家平台的表）：跨仓库不加外键，普通列 + 索引；四张表之间加外键。
--
-- 状态机（契约 5.2）：PENDING_PAYMENT → PAID → SHIPPED → DELIVERED → COMPLETED；PENDING_PAYMENT → CANCELLED（超时）。
-- 每次迁移在同一事务写入对应时刻列，之后不改。

CREATE TABLE purchase_orders (
    id                    BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_token          VARCHAR(32)  NOT NULL,
    merchant_store_id     BIGINT       NOT NULL,
    order_no              VARCHAR(32)  NOT NULL,
    status                VARCHAR(24)  NOT NULL,
    cancel_reason         VARCHAR(32),
    shipping_method       VARCHAR(16)  NOT NULL,
    goods_amount          BIGINT       NOT NULL,

    -- 🔒 收货地址快照（PII，日志禁记），格式同 shop_orders.ship_*。
    ship_receiver_name    VARCHAR(40)  NOT NULL,
    ship_receiver_phone   VARCHAR(16)  NOT NULL,
    ship_provinsi         VARCHAR(60)  NOT NULL,
    ship_kota_kabupaten   VARCHAR(60)  NOT NULL,
    ship_kecamatan        VARCHAR(60)  NOT NULL,
    ship_address_line     VARCHAR(120) NOT NULL,
    ship_kode_pos         VARCHAR(5)   NOT NULL,

    store_name_snapshot   VARCHAR(80)  NOT NULL,
    store_phone_snapshot  VARCHAR(16)  NOT NULL,

    payment_deadline      TIMESTAMPTZ  NOT NULL,
    -- 当前支付意图（到账事件据此回找进货单）；未发起支付为 NULL。
    payment_intent_token  VARCHAR(64),

    paid_at               TIMESTAMPTZ,
    shipped_at            TIMESTAMPTZ,
    delivered_at          TIMESTAMPTZ,
    completed_at          TIMESTAMPTZ,
    cancelled_at          TIMESTAMPTZ,
    -- 签收走的是哪条出口（ADMIN_MARK / AUTO_TIMEOUT），只作留痕。
    delivery_source       VARCHAR(24),

    -- 乐观锁：支付回调与超时取消同时读到 PENDING_PAYMENT 时，后提交者整体回滚（同 shop_orders.version）。
    version               BIGINT       NOT NULL DEFAULT 0,
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_purchase_orders_token    UNIQUE (public_token),
    CONSTRAINT uq_purchase_orders_order_no UNIQUE (order_no),
    CONSTRAINT ck_purchase_orders_status CHECK (status IN (
        'PENDING_PAYMENT', 'PAID', 'SHIPPED', 'DELIVERED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_purchase_orders_cancel_reason CHECK (
        (status = 'CANCELLED' AND cancel_reason IN ('PAYMENT_TIMEOUT'))
        OR (status <> 'CANCELLED' AND cancel_reason IS NULL)),
    CONSTRAINT ck_purchase_orders_shipping_method CHECK (shipping_method IN ('FREE', 'COD_SHIPPING')),
    CONSTRAINT ck_purchase_orders_goods_amount CHECK (goods_amount >= 0),
    CONSTRAINT ck_purchase_orders_delivery_source CHECK (
        delivery_source IS NULL OR delivery_source IN ('ADMIN_MARK', 'AUTO_TIMEOUT'))
);

-- 列表（门店「我的进货单」与 ops 门店详情）+ 按状态筛选；汇总由第二条覆盖。
CREATE INDEX idx_purchase_orders_store_created
    ON purchase_orders (merchant_store_id, created_at DESC, id DESC);
CREATE INDEX idx_purchase_orders_store_status_created
    ON purchase_orders (merchant_store_id, status, created_at DESC, id DESC);
-- 超时取消扫描。
CREATE INDEX idx_purchase_orders_pending_deadline
    ON purchase_orders (status, payment_deadline)
    WHERE status = 'PENDING_PAYMENT';
-- 到账回找。
CREATE INDEX idx_purchase_orders_intent
    ON purchase_orders (payment_intent_token)
    WHERE payment_intent_token IS NOT NULL;
-- 履约扫描（自动签收 / 自动完成）。
CREATE INDEX idx_purchase_orders_fulfillment
    ON purchase_orders (status, shipped_at, delivered_at)
    WHERE status IN ('SHIPPED', 'DELIVERED');

-- 明细：建单时写入后不改（商品名、规格名、主图快照）。
CREATE TABLE purchase_order_lines (
    id                    BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id     BIGINT       NOT NULL REFERENCES purchase_orders (id) ON DELETE CASCADE,
    line_no               INT          NOT NULL,
    sku_id                BIGINT       NOT NULL,
    sku_token_snapshot    VARCHAR(32)  NOT NULL,
    product_name_snapshot VARCHAR(120) NOT NULL,
    spec_name_snapshot    VARCHAR(60)  NOT NULL,
    image_key_snapshot    VARCHAR(255),
    wholesale_price       BIGINT       NOT NULL,
    qty                   INT          NOT NULL,
    subtotal              BIGINT       NOT NULL,
    CONSTRAINT uq_purchase_order_lines_line_no UNIQUE (purchase_order_id, line_no),
    CONSTRAINT uq_purchase_order_lines_sku     UNIQUE (purchase_order_id, sku_id),
    CONSTRAINT ck_purchase_order_lines_line_no CHECK (line_no >= 1),
    CONSTRAINT ck_purchase_order_lines_price   CHECK (wholesale_price >= 0),
    CONSTRAINT ck_purchase_order_lines_qty     CHECK (qty BETWEEN 1 AND 9999),
    CONSTRAINT ck_purchase_order_lines_subtotal CHECK (subtotal = wholesale_price * qty)
);

-- 发货包裹：一单可多包裹，TailTopia ops 发货时写入。
CREATE TABLE purchase_order_shipments (
    id                    BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id     BIGINT       NOT NULL REFERENCES purchase_orders (id) ON DELETE CASCADE,
    carrier               VARCHAR(32)  NOT NULL,
    tracking_no           VARCHAR(64)  NOT NULL,
    tracking_url          VARCHAR(512),
    shipped_at            TIMESTAMPTZ  NOT NULL,
    created_by            BIGINT,
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_purchase_order_shipments_order
    ON purchase_order_shipments (purchase_order_id, shipped_at, id);

-- 建单幂等（AD-17）：与建单同一事务落库，只记成功建单（被拒的请求随事务回滚，不留记录）；保留 ≥ 7 天后可清理。
-- request_digest = 规范化请求体的 SHA-256 十六进制（契约 5.4）。
CREATE TABLE purchase_order_idempotency (
    merchant_store_id     BIGINT       NOT NULL,
    idempotency_key       CHAR(22)     NOT NULL,
    request_digest        CHAR(64)     NOT NULL,
    purchase_order_id     BIGINT       NOT NULL REFERENCES purchase_orders (id) ON DELETE CASCADE,
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_purchase_order_idempotency PRIMARY KEY (merchant_store_id, idempotency_key)
);
CREATE INDEX idx_purchase_order_idempotency_created
    ON purchase_order_idempotency (created_at);
