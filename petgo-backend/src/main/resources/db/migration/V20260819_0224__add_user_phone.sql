-- 工作线：V1.1.6（本分支迁移从 V105 起，V101–V104 归 hex/v1.1.4）
--
-- V1.1.6 Story 7.1 · FR-70：用户手机号（选填，供运营做流失召回）。
--
-- 设计要点：
--   1. **可空**：选填字段，绝大多数用户不会填；NULL = 未填写（后台按此分组筛选）。
--
--   2. 🛡 **属个人信息**。项目已有的请求/响应日志脱敏是**按字段名整串打码**的，
--      名单里已经有 `phone` —— 所以这一列**必须叫 phone**。
--      叫 phoneNumber / mobile / contact 都不会命中，日志里就会明晃晃出现真实号码，
--      **而且不会有任何报错**。命名本身就是护栏，别改。
--
--   3. **不验证、不用于登录**（FR-70 明确排除）：这里只是一个联系方式，
--      没有唯一约束 —— 两个人填同一个号是可能的（家庭共用），不该被拦。
--
--   4. **允许清空**：个人数据保护法赋予删除权，用户清空保存即写回 NULL（视为撤回），
--      随后在后台重新落入「未填写」分组、可再次被纳入催填范围。
--
--   5. 长度 32：归一后形如 `+628xxxxxxxxxx`，留足余量。

ALTER TABLE users ADD COLUMN phone VARCHAR(32);

COMMENT ON COLUMN users.phone IS
    '手机号（FR-70，选填、不验证、不用于登录）。NULL = 未填写 / 已撤回。个人信息：禁止写入日志（LogSanitizer 按字段名打码，故列名与 JSON 字段名必须都是 phone）。';
