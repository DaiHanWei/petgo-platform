-- V1.4.0 multi-pet · Story 2.2 —— 宠物名额月租：购买表 + 名额表（AD-5，照 keepsake_purchases）。
--
-- 🔴 不碰共享 CHECK：ck_payment_intents_purpose（地基 0.1 已含 PET_SLOT_RENT）、ck_keepsake_purchases_sku 本迁移一概不动。
-- 🔴 相对 AD-5 的补充：两表都加 public_token（项目强制「对外标识不可枚举」——续租按名额寻址、App 轮询按购买单寻址）。
-- 🔴 本迁移只建表，不回填、不改写任何既有行。

-- ---------------------------------------------------------------------------
-- 购买记录：新租 / 续租 / 运营补发（ADMIN_GRANT，Story 4.3 使用）共用。资金流水：注销随 users 行匿名化口径不删。
-- ---------------------------------------------------------------------------
CREATE TABLE pet_slot_purchases (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_token       VARCHAR(32)   NOT NULL,
    user_id            BIGINT        NOT NULL,
    kind               VARCHAR(16)   NOT NULL,
    quantity           INT           NOT NULL,
    unit_price         BIGINT        NOT NULL,
    total              BIGINT        NOT NULL,
    channel            VARCHAR(16)   NULL,
    payment_intent_id  BIGINT        NULL,
    idem_key           VARCHAR(160)  NOT NULL,
    status             VARCHAR(16)   NOT NULL,
    rental_ids         BIGINT[]      NULL,
    days               INT           NOT NULL DEFAULT 30,
    operator_admin_id  BIGINT        NULL,
    reason             VARCHAR(200)  NULL,
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    paid_at            TIMESTAMPTZ   NULL,
    CONSTRAINT uq_pet_slot_purchases_public_token UNIQUE (public_token),
    CONSTRAINT uq_pet_slot_purchases_payment_intent UNIQUE (payment_intent_id),
    CONSTRAINT uq_pet_slot_purchases_idem_key UNIQUE (idem_key),
    CONSTRAINT ck_pet_slot_purchases_kind CHECK (kind IN ('RENT', 'RENEW', 'ADMIN_GRANT')),
    CONSTRAINT ck_pet_slot_purchases_quantity CHECK (quantity BETWEEN 1 AND 5),
    CONSTRAINT ck_pet_slot_purchases_unit_price CHECK (unit_price >= 0),
    CONSTRAINT ck_pet_slot_purchases_total CHECK (total >= 0),
    CONSTRAINT ck_pet_slot_purchases_channel CHECK (channel IN ('QRIS', 'PAWCOIN')),
    CONSTRAINT ck_pet_slot_purchases_status CHECK (status IN
        ('PENDING', 'PAID', 'FAILED', 'EXPIRED', 'ORPHAN_PAID', 'OVERPAID')),
    CONSTRAINT ck_pet_slot_purchases_days CHECK (days >= 1)
);

-- 后台购买记录（Story 4.3）游标。不加「每人一笔 PENDING」部分唯一索引：允许新租与续租各有一笔待付（Story 2.2 Dev Notes）。
CREATE INDEX ix_pet_slot_purchases_user_created ON pet_slot_purchases (user_id, created_at DESC, id DESC);

COMMENT ON TABLE pet_slot_purchases IS
    '宠物名额月租购买记录（V1.4.0 multi-pet AD-5）：新租 / 续租 / 运营补发共用。资金流水，注销随 users 行匿名化口径不删。';
COMMENT ON COLUMN pet_slot_purchases.id IS '主键（内部用，不外露）。';
COMMENT ON COLUMN pet_slot_purchases.public_token IS '不可枚举对外标识（App 轮询 purchaseToken，32 位 base62）。';
COMMENT ON COLUMN pet_slot_purchases.user_id IS '购买人（照 keepsake_purchases 不加 FK；注销时 users 行匿名化不删）。';
COMMENT ON COLUMN pet_slot_purchases.kind IS 'RENT 新租 / RENEW 续租 / ADMIN_GRANT 运营补发（Story 4.3）。';
COMMENT ON COLUMN pet_slot_purchases.quantity IS '名额个数（1–5）：新租 = 新建名额数；续租 = 所选名额数；补发 = 1。';
COMMENT ON COLUMN pet_slot_purchases.unit_price IS '下单时的月租单价快照（IDR / 名额 / 30 天）；ADMIN_GRANT = 0。改价不影响已生成的单。';
COMMENT ON COLUMN pet_slot_purchases.total IS '本单总额（IDR）= 单价 × 个数；QRIS = 意图金额，PawCoin = 扣币额；ADMIN_GRANT = 0。';
COMMENT ON COLUMN pet_slot_purchases.channel IS '支付渠道：QRIS / PAWCOIN（虚拟商品不支持混合支付）；ADMIN_GRANT 为 NULL。';
COMMENT ON COLUMN pet_slot_purchases.payment_intent_id IS 'QRIS 对应的 payment_intents.id（唯一：回调与轮询只生效一次）；PawCoin / 补发为 NULL。';
COMMENT ON COLUMN pet_slot_purchases.idem_key IS
    '幂等键 PET_SLOT_RENT:{userId}:{kind}:{clientKey}:{channel}（按渠道加后缀，照 KeepsakePurchaseService）；QRIS 行另加 :{intentId}'
    '（同键重开换新意图时另起一行、旧行置 EXPIRED，不改挂）；唯一兜底。';
COMMENT ON COLUMN pet_slot_purchases.status IS
    'PENDING 待付 / PAID 已付已发放 / FAILED 付款失败 / EXPIRED 付款超时或同键重开被替换（失败与超时不增加名额；其意图若仍到账照常发放）/ '
    'ORPHAN_PAID 已到账但发放失败（交人工）/ OVERPAID 已到账但发放会让生效名额超过 5，未发放（交人工退款）。';
COMMENT ON COLUMN pet_slot_purchases.rental_ids IS
    '涉及的 pet_slot_rentals.id：续租下单时 = 所选名额；新租到账后回填新建名额；续租到账时某名额已过期则记实际新建的名额。';
COMMENT ON COLUMN pet_slot_purchases.days IS '每个名额本单发放 / 延长的天数（月租恒 30；补发由运营填写）。';
COMMENT ON COLUMN pet_slot_purchases.operator_admin_id IS '运营补发的操作人（admin_accounts.id，仅 ADMIN_GRANT，Story 4.3）。';
COMMENT ON COLUMN pet_slot_purchases.reason IS '运营补发原因（仅 ADMIN_GRANT，Story 4.3）。';
COMMENT ON COLUMN pet_slot_purchases.created_at IS '下单时刻（UTC）。';
COMMENT ON COLUMN pet_slot_purchases.paid_at IS '到账 / 扣币 / 补发时刻（UTC）。';

-- ---------------------------------------------------------------------------
-- 名额：每个名额一行（同一次租的 N 个名额各自一行、各自续租与提醒）。名额数实时计算，只数 ACTIVE 且未过期的行。
-- ---------------------------------------------------------------------------
CREATE TABLE pet_slot_rentals (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_token  VARCHAR(32)   NOT NULL,
    user_id       BIGINT        NOT NULL,
    source        VARCHAR(16)   NOT NULL,
    starts_at     TIMESTAMPTZ   NOT NULL,
    expires_at    TIMESTAMPTZ   NOT NULL,
    status        VARCHAR(16)   NOT NULL DEFAULT 'ACTIVE',
    reminded_at   TIMESTAMPTZ   NULL,
    expired_at    TIMESTAMPTZ   NULL,
    purchase_id   BIGINT        NOT NULL REFERENCES pet_slot_purchases (id),
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_pet_slot_rentals_public_token UNIQUE (public_token),
    CONSTRAINT ck_pet_slot_rentals_source CHECK (source IN ('RENT', 'ADMIN_GRANT')),
    CONSTRAINT ck_pet_slot_rentals_status CHECK (status IN ('ACTIVE', 'EXPIRED')),
    CONSTRAINT ck_pet_slot_rentals_window CHECK (expires_at > starts_at)
);

-- 到期扫描（Story 2.3）。
CREATE INDEX ix_pet_slot_rentals_status_expires ON pet_slot_rentals (status, expires_at);
-- 名额计算 / 名额管理页。
CREATE INDEX ix_pet_slot_rentals_user_status ON pet_slot_rentals (user_id, status);
-- 按购买单查发放的名额（FK 列，后台购买记录 / 运维）。
CREATE INDEX ix_pet_slot_rentals_purchase ON pet_slot_rentals (purchase_id);

COMMENT ON TABLE pet_slot_rentals IS
    '宠物月租名额（V1.4.0 multi-pet AD-5）：每个名额一行；RENT 用户租用 / ADMIN_GRANT 运营补发，同表同状态参与到期提醒与到期。';
COMMENT ON COLUMN pet_slot_rentals.id IS '主键（内部用，不外露）。';
COMMENT ON COLUMN pet_slot_rentals.public_token IS '不可枚举对外标识（续租接口按它寻址，32 位 base62）。';
COMMENT ON COLUMN pet_slot_rentals.user_id IS '名额所属用户（照 keepsake_purchases 不加 FK）。';
COMMENT ON COLUMN pet_slot_rentals.source IS 'RENT 用户租用 / ADMIN_GRANT 运营补发（Story 4.3）。';
COMMENT ON COLUMN pet_slot_rentals.starts_at IS '生效时刻（UTC）= 付款成功 / 补发时刻。';
COMMENT ON COLUMN pet_slot_rentals.expires_at IS '到期时刻（UTC）；续租在原到期日上 +30 天。';
COMMENT ON COLUMN pet_slot_rentals.status IS 'ACTIVE 生效中 / EXPIRED 已到期（Story 2.3 扫描置位）。名额只数 ACTIVE 且 expires_at > now 的行。';
COMMENT ON COLUMN pet_slot_rentals.reminded_at IS '到期前提醒已发时刻（Story 2.3）；续租时清空，让新到期日再提醒一次。';
COMMENT ON COLUMN pet_slot_rentals.expired_at IS '被置为 EXPIRED 的时刻（Story 2.3）。';
COMMENT ON COLUMN pet_slot_rentals.purchase_id IS '首次发放本名额的购买行（pet_slot_purchases.id）。';
COMMENT ON COLUMN pet_slot_rentals.created_at IS '行创建时刻（UTC）。';
