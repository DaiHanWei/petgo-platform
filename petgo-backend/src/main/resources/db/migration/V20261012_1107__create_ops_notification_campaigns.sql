-- V1.3.4 app 主题 · Story 6.1（FR-138 / AD-17 / 决策日志 D-16、D-20、D-24）
-- 运营系统通知「发送活动」。本主题建表 + 发送核心；后台发送页（AB-31）在 admin 主题，调用本主题的服务方法写入。
CREATE TABLE ops_notification_campaigns (
    id                BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 对外标识（不可枚举，由 com.tailtopia.ops.OpsTokenGenerator 生成 22 位 base62；列宽 32 与 ops_popups 一致）。
    -- 埋点 campaign_id、notifications.target_ref 都用它（D-24）。
    public_token      VARCHAR(32)   NOT NULL,
    -- 运营须填 EN / ID 两种语言（PRD §3.7）；长度 = notifications.title / body 列长。
    title_id          VARCHAR(120)  NOT NULL,
    title_en          VARCHAR(120)  NOT NULL,
    body_id           VARCHAR(255)  NOT NULL,
    body_en           VARCHAR(255)  NOT NULL,
    -- 跳转目标：列名、类型、默认值、CHECK 与 ops_popups（V20261012_1106）同一口径（AD-14 / AD-16）。
    -- 取值语义与校验唯一口径 = com.tailtopia.ops.target.OpsTargetPolicy（Story 5.1）。
    target_type       VARCHAR(16)   NOT NULL DEFAULT 'NONE',
    target_value      VARCHAR(512)  NULL,
    -- 人群规格（D-16）。IDS 模式的用户 id 不进 JSON，存子表 ops_notification_campaign_targets。
    audience_spec     JSONB         NOT NULL,
    -- 为空 = 立即发送；非空 = 到点由定时扫描发送（Story 6.2）。
    scheduled_at      TIMESTAMPTZ,
    status            VARCHAR(16)   NOT NULL DEFAULT 'PENDING',
    -- 成功写入通知中心的人数（= 触达人数）。
    recipient_count   INTEGER       NOT NULL DEFAULT 0,
    -- 通知中心写入失败或推送重试 3 次仍失败的人数（Story 6.2）。
    failed_count      INTEGER       NOT NULL DEFAULT 0,
    -- IDS 模式里被跳过的无效 id 个数（不存在 / 注销 / 封号 / 停用 / 虚拟号 / 非普通用户）。
    skipped_count     INTEGER       NOT NULL DEFAULT 0,
    -- 后台账号 id（admin_accounts.id）；不加外键：与 App 账号体系隔离，后台账号可被删。
    created_by        BIGINT,
    started_at        TIMESTAMPTZ,
    -- 发送线程每推进一步刷新；SENDING 且超过 15 分钟未刷新 → PARTIAL_FAILED（D-20）。
    last_progress_at  TIMESTAMPTZ,
    finished_at       TIMESTAMPTZ,
    canceled_at       TIMESTAMPTZ,
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_ops_notification_campaigns_token UNIQUE (public_token),
    CONSTRAINT ck_ops_notification_campaigns_status CHECK (status IN
        ('PENDING', 'SENDING', 'DONE', 'PARTIAL_FAILED', 'CANCELED')),
    CONSTRAINT ck_ops_notification_campaigns_target_type
        CHECK (target_type IN ('NONE', 'PRODUCT', 'CATEGORY', 'APP_PAGE', 'EXTERNAL')),
    CONSTRAINT ck_ops_notification_campaigns_target_value CHECK ((target_type = 'NONE') = (target_value IS NULL)),
    -- 先判键存在、再 COALESCE：缺 mode 或 mode 为 JSON null 时 ->> 返回 NULL，
    -- NULL IN (...) 为 NULL，CHECK 会视为通过。
    CONSTRAINT ck_ops_notification_campaigns_audience_mode CHECK (
        audience_spec ? 'mode' AND COALESCE(audience_spec ->> 'mode', '') IN ('ALL', 'FILTER', 'IDS')),
    CONSTRAINT ck_ops_notification_campaigns_counts CHECK (
        recipient_count >= 0 AND failed_count >= 0 AND skipped_count >= 0)
);

-- 定时扫描：取到期的 PENDING；超时扫：取 SENDING。
CREATE INDEX ix_ops_notification_campaigns_status_sched
    ON ops_notification_campaigns (status, scheduled_at);

-- IDS 模式的指定用户。user_id 不加外键：后台 CSV 里的无效 id 也要落库，发送时才能「跳过并计数」。
CREATE TABLE ops_notification_campaign_targets (
    campaign_id  BIGINT  NOT NULL REFERENCES ops_notification_campaigns (id) ON DELETE CASCADE,
    user_id      BIGINT  NOT NULL,
    PRIMARY KEY (campaign_id, user_id)
);
-- 注销级联按 user_id 删（NotificationDeletionService）。
CREATE INDEX ix_ops_notification_campaign_targets_user
    ON ops_notification_campaign_targets (user_id);

COMMENT ON TABLE ops_notification_campaigns IS
    '运营系统通知发送活动（FR-138 / AD-17）。状态机 PENDING→SENDING→DONE|PARTIAL_FAILED，PENDING 可→CANCELED；条件更新防重复执行。';
COMMENT ON COLUMN ops_notification_campaigns.audience_spec IS
    '人群规格 JSON（D-16）：{mode: ALL|FILTER|IDS, registeredFrom?, registeredTo?, activeFrom?, activeTo?, hasPet?, species?, hasShopOrder?, hasPhone?}；缺键=不筛；日期按 WIB 自然日含两端。';
COMMENT ON TABLE ops_notification_campaign_targets IS
    'IDS 模式的指定用户 id（不进 JSON）。无外键：无效 id 发送时跳过并计入 skipped_count。';
