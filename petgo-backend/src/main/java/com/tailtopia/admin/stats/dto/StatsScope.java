package com.tailtopia.admin.stats.dto;

/**
 * 双口径（V1.1.6 Story 15.1 · AC2）。
 *
 * <p>⚠️ <b>两个口径回答的是不同问题，不是同一个数的两种算法。</b>
 * 混为一谈会让判读失真 —— 所以界面上它们是**互斥单选**，而不是两列并排。
 */
public enum StatsScope {

    /**
     * 口径A · <b>内容质量</b>：按帖子**发布时间**筛区间，积分取其**至今累计**的赞/评总数。
     *
     * <p>回答「这段时间发的内容质量如何」—— 辅助装饰标签选品与内容质量汇报。
     */
    CONTENT_QUALITY,

    /**
     * 口径B · <b>平台活跃度</b>：**不筛发布时间**（全部已发布帖子都参与），
     * 积分只计**该区间内新增**的赞/评次数。
     *
     * <p>回答「这段时间平台用户互动活跃情况」—— 能反映**老帖子被重新带火**这类
     * 口径A 完全看不到的情况。
     */
    PLATFORM_ACTIVITY
}
