package com.tailtopia.shop.review.domain;

/**
 * 评价审核状态（Story 7.1）。
 *
 * <p>🔴 <b>同步过滤，不走「先发布后审核」</b>：提交那一刻就有结论。
 * 商品评价是带图的公开内容，先发后审意味着违规内容在被发现前对所有潜在买家可见，
 * 而它旁边就是我们自己在卖的商品。
 */
public enum ReviewStatus {
    /** 通过，已发布。详情页评价区只读这一态。 */
    PUBLISHED,
    /**
     * 被拦截，<b>不发布</b>。
     *
     * <p>🔴 <b>不进人工队列</b>：用户停留编辑态、可改后重提（F13 输入类失败统一口径）。
     * 排一条人工队列只会让用户等一个他自己两秒就能解决的问题。
     */
    BLOCKED,
    /**
     * 三方审核不可用时的待重试态。
     *
     * <p>🔴 <b>fail-closed：不发布</b>。但这不是用户的错，所以<b>不让他改文案</b> ——
     * 由定时重试自己收敛。与 {@link #BLOCKED} 分开正是为了不把系统故障说成用户违规。
     */
    PENDING
}
