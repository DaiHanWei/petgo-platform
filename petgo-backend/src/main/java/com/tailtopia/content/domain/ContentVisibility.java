package com.tailtopia.content.domain;

/**
 * 内容可见范围（V1.1.2 Story 4.1 · FR-83 · AD-4）。
 *
 * <p><b>通用字段</b>：三类内容（Diary / Moment / Tips）统一携带，未做 Diary 专属布尔。
 *
 * <p>⚠️ <b>三分法判定口径（NFR-4，安全攸关）</b>——过滤范围严格限定「平台自动分发」：
 * <ul>
 *   <li><b>作者自视</b>（成长档案时间线 / 日历 / 当天详情 / 我的发布）→ <b>不过滤</b>；</li>
 *   <li><b>平台自动分发</b>（Feed / 话题聚合 / 他人主页 / 任何公开位）→ <b>按 PUBLIC 过滤</b>；</li>
 *   <li><b>作者主动分享</b>（宠物名片 H5，FR-14）→ <b>不过滤</b>（OQ-18 2026-08-03 拍板：
 *       visibility 约束的是平台自动分发，不约束用户自己按下分享键的行为）。</li>
 * </ul>
 * 把过滤误加到第一或第三类上，就直接摧毁了 FR-83 的产品语义（作者看不到自己的私密日记 /
 * 主动分享出去的名片缺内容）。
 */
public enum ContentVisibility {

    /** 平台可自动分发（默认值；存量内容一律为此）。 */
    PUBLIC,

    /** 仅作者自视：不进 Feed / 聚合 / 他人主页；作者自己的档案与主动分享不受影响。 */
    PRIVATE
}
