import 'package:flutter_test/flutter_test.dart';
import 'package:tailtopia/features/me/domain/phone_mask.dart';

/// Story 7.2 · 「我的」页常驻入口的**脱敏展示**（PRD §2.2，对齐 UI 稿 05b 屏）。
///
/// 规则：保留国家码/前缀与**末四位**，中间遮蔽。
/// ⚠️ 脱敏只是**显示层** —— 编辑抽屉里必须是完整号码，否则用户改不了自己的号。
void main() {
  group('保留前缀与末四位', () {
    /// 期望值以 **UI 稿 05b 屏**为准：`+62 812-••••-7890`
    /// ⇒ 前缀保留 5 位数字（国家码 2 + 运营商 3）、末四位保留、其余遮蔽。
    test('标准 +62 号码', () {
      expect(PhoneMask.mask('+6281234567890'), '+62 812••••7890');
    });

    test('刚好遮不动一位 → 原样返回（别输出"看着像脱敏其实没遮"的结果）', () {
      expect(PhoneMask.mask('+628121234'), '+628121234');
    });
  });

  group('边界：太短就不该硬遮', () {
    /// 号码短到"遮了就没意义"时，直接原样返回 —— 遮成 `+62 •••` 既不可读、
    /// 也没有多保护什么（用户看的是**自己的**号码，脱敏是为了防肩窥，不是防他自己）。
    test('短于阈值 → 原样返回', () {
      expect(PhoneMask.mask('+62812'), '+62812');
      expect(PhoneMask.mask('0812'), '0812');
    });

    test('空 / null → 原样（由调用方决定显示占位文案）', () {
      expect(PhoneMask.mask(null), isNull);
      expect(PhoneMask.mask(''), '');
    });
  });

  group('不假设一定有 + 前缀', () {
    /// 7-1 的校验**刻意放宽**（印尼人真实会写 `0812...`、`62812...`、带空格和横线的都有），
    /// 所以脱敏不能假设固定格式，否则会在真实数据上崩或输出乱码。
    test('本地格式 08xx 也能脱敏（前缀不以 62 开头 → 不插空格）', () {
      expect(PhoneMask.mask('081234567890'), '08123•••7890');
    });

    test('带空格与横线的输入不影响末四位判定', () {
      expect(PhoneMask.mask('+62 812-3456-7890'), endsWith('7890'));
    });
  });
}
